import type { Collection, SavedContent } from './types';

// Palette gradients for collection card headers
const COLLECTION_GRADIENTS = [
  'linear-gradient(135deg, #4338ca 0%, #6366f1 100%)', // Indigo
  'linear-gradient(135deg, #059669 0%, #10b981 100%)', // Emerald
  'linear-gradient(135deg, #d97706 0%, #f59e0b 100%)', // Amber
  'linear-gradient(135deg, #7c3aed 0%, #a855f7 100%)', // Purple
  'linear-gradient(135deg, #db2777 0%, #ec4899 100%)', // Pink
  'linear-gradient(135deg, #0284c7 0%, #38bdf8 100%)', // Sky
  'linear-gradient(135deg, #e11d48 0%, #f43f5e 100%)', // Rose
];

export function generateAutoCollections(items: SavedContent[]): Collection[] {
  if (!items || items.length === 0) return [];

  const autoCollections: Collection[] = [];
  const processedItemIds = new Set<string>();

  // Rule 1: Frontend & React cluster
  const frontendItems = items.filter((item) => {
    const text = `${item.title} ${item.category} ${item.subcategory || ''} ${(item.tags || []).join(' ')}`.toLowerCase();
    return text.includes('react') || text.includes('frontend') || text.includes('javascript') || text.includes('next.js') || text.includes('css') || text.includes('ui');
  });
  if (frontendItems.length > 0) {
    autoCollections.push({
      id: 'auto-frontend-react',
      title: 'React & Frontend Architecture',
      description: 'Component architecture, state management, render optimizations, and modern web frameworks.',
      icon: '⚛️',
      isAutoGenerated: true,
      category: 'Programming',
      tags: ['React', 'Performance', 'Frontend', 'Next.js'],
      itemIds: frontendItems.map((i) => i.id),
      createdAt: 'Auto-clustered by Gemini',
      color: COLLECTION_GRADIENTS[0],
    });
    frontendItems.forEach((i) => processedItemIds.add(i.id));
  }

  // Rule 2: Nutrition, Food & Health
  const foodItems = items.filter((item) => {
    const text = `${item.title} ${item.category} ${item.subcategory || ''} ${(item.tags || []).join(' ')}`.toLowerCase();
    return text.includes('food') || text.includes('cook') || text.includes('recipe') || text.includes('protein') || text.includes('breakfast') || text.includes('diet');
  });
  if (foodItems.length > 0) {
    autoCollections.push({
      id: 'auto-healthy-nutrition',
      title: 'Healthy Fuel & High-Protein Recipes',
      description: 'Quick nutrient-dense meals, high-protein recipes, macro breakdowns, and kitchen workflows.',
      icon: '🥗',
      isAutoGenerated: true,
      category: 'Cooking & Food',
      tags: ['Nutrition', 'HighProtein', 'Recipes', 'MealPrep'],
      itemIds: foodItems.map((i) => i.id),
      createdAt: 'Auto-clustered by Gemini',
      color: COLLECTION_GRADIENTS[1],
    });
    foodItems.forEach((i) => processedItemIds.add(i.id));
  }

  // Rule 3: Cloud, DevOps & Infrastructure
  const devopsItems = items.filter((item) => {
    const text = `${item.title} ${item.category} ${item.subcategory || ''} ${(item.tags || []).join(' ')}`.toLowerCase();
    return text.includes('cloud') || text.includes('aws') || text.includes('docker') || text.includes('devops') || text.includes('kubernetes') || text.includes('deploy');
  });
  if (devopsItems.length > 0) {
    autoCollections.push({
      id: 'auto-cloud-devops',
      title: 'Cloud Infrastructure & DevOps Pipelines',
      description: 'Containerization, CI/CD, AWS deployments, reverse proxies, and production server setup.',
      icon: '☁️',
      isAutoGenerated: true,
      category: 'Cloud',
      tags: ['AWS', 'Docker', 'DevOps', 'Infrastructure'],
      itemIds: devopsItems.map((i) => i.id),
      createdAt: 'Auto-clustered by Gemini',
      color: COLLECTION_GRADIENTS[2],
    });
    devopsItems.forEach((i) => processedItemIds.add(i.id));
  }

  // Rule 4: Marketing, Storytelling & Business
  const marketingItems = items.filter((item) => {
    const text = `${item.title} ${item.category} ${item.subcategory || ''} ${(item.tags || []).join(' ')}`.toLowerCase();
    return text.includes('market') || text.includes('brand') || text.includes('story') || text.includes('business') || text.includes('growth') || text.includes('sales');
  });
  if (marketingItems.length > 0) {
    autoCollections.push({
      id: 'auto-brand-storytelling',
      title: 'Brand Strategy & Narrative Growth',
      description: 'Story arcs, positioning frameworks, audience hooks, and converting attention into action.',
      icon: '🎯',
      isAutoGenerated: true,
      category: 'Marketing',
      tags: ['Branding', 'Storytelling', 'Marketing', 'Strategy'],
      itemIds: marketingItems.map((i) => i.id),
      createdAt: 'Auto-clustered by Gemini',
      color: COLLECTION_GRADIENTS[3],
    });
    marketingItems.forEach((i) => processedItemIds.add(i.id));
  }

  // Dynamic Rule: For any remaining or other categories not yet grouped into specific thematic buckets
  const remainingCategories = Array.from(
    new Set(
      items
        .filter((i) => !processedItemIds.has(i.id))
        .map((i) => i.category)
        .filter(Boolean)
    )
  );

  let gradIdx = 4;
  for (const cat of remainingCategories) {
    const catItems = items.filter((i) => i.category === cat && !processedItemIds.has(i.id));
    if (catItems.length > 0) {
      const icon = getCategoryIcon(cat);
      autoCollections.push({
        id: `auto-${cat.toLowerCase().replace(/[^a-z0-9]/g, '-')}`,
        title: `${cat} Vault`,
        description: `Automatically organized knowledge and insights detected in ${cat}.`,
        icon,
        isAutoGenerated: true,
        category: cat,
        tags: [cat],
        itemIds: catItems.map((i) => i.id),
        createdAt: 'Auto-clustered by Gemini',
        color: COLLECTION_GRADIENTS[gradIdx % COLLECTION_GRADIENTS.length],
      });
      gradIdx++;
    }
  }

  return autoCollections;
}

function getCategoryIcon(cat: string): string {
  const c = cat.toLowerCase();
  if (c.includes('code') || c.includes('program')) return '💻';
  if (c.includes('cook') || c.includes('food')) return '🍳';
  if (c.includes('cloud') || c.includes('devops')) return '☁️';
  if (c.includes('market') || c.includes('brand')) return '🎯';
  if (c.includes('ai') || c.includes('ml')) return '🤖';
  if (c.includes('design') || c.includes('art')) return '🎨';
  if (c.includes('finance') || c.includes('crypto')) return '📈';
  if (c.includes('fitness') || c.includes('health')) return '💪';
  if (c.includes('book') || c.includes('learn')) return '📚';
  return '📁';
}

